import logging
from typing import List, Dict, Any
from app.schemas.chat import StructuredResource
from app.services.guardrails.models import CitationValidationResult

logger = logging.getLogger(__name__)

class CitationGuard:
    def validate_citations(self, generated_resources: List[StructuredResource], retrieved_chunks: List[Dict[str, Any]]) -> CitationValidationResult:
        """
        Validates that every citation generated by the LLM corresponds to an actual retrieved document and page.
        """
        if not generated_resources:
            return CitationValidationResult(valid=True, reason="No citations provided.")
            
        valid_doc_pages = set()
        for chunk in retrieved_chunks:
            doc_name = str(chunk['metadata'].get('document_name', '')).strip()
            page_num = str(chunk['metadata'].get('page_number', '')).strip()
            if doc_name:
                valid_doc_pages.add((doc_name, page_num))
                
        for res in generated_resources:
            res_doc = str(res.document_name).strip()
            res_page = str(res.page_number).strip()
            
            # Simple exact match (in a production system, fuzzy matching might be needed)
            if (res_doc, res_page) not in valid_doc_pages:
                logger.warning(f"CitationGuard: Invalid citation detected: {res_doc} Page {res_page}")
                return CitationValidationResult(
                    valid=False, 
                    reason=f"Fabricated citation detected: '{res_doc}' on page '{res_page}' was not in the retrieved context."
                )
                
        return CitationValidationResult(valid=True, reason="All citations match retrieved context.")

citation_guard = CitationGuard()
